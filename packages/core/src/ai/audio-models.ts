import type { ModelDef, PriceQuote } from './models';

/**
 * ElevenLabs bills in plan credits, so dollar figures are estimates from your
 * plan's rate. Override them with the ELEVENLABS_* pricing env vars.
 */
export const audioRates = {
  ttsPer1kChars: 0.22,
  musicPerMinute: 0.8,
  sfxPerGeneration: 0.044,
  stsPerMinute: 0.22,
  isolatePerMinute: 0.22,
  transcribePerMinute: 0.0067,
  dubPerMinute: 0.66,
  stemsPerRun: 0.03,
  openaiTranscribePerMinute: 0.006,
};
export type AudioRates = typeof audioRates;

export function setAudioRates(overrides: Partial<AudioRates>) {
  for (const [k, v] of Object.entries(overrides)) {
    if (typeof v === 'number' && Number.isFinite(v) && v >= 0) (audioRates as Record<string, number>)[k] = v;
  }
}

const perMinute = (rate: number, seconds: number, label: string): PriceQuote => ({
  usd: (rate * Math.max(seconds, 1)) / 60,
  detail: `${(Math.max(seconds, 1) / 60).toFixed(2)} min × $${rate.toFixed(3)}/min ${label}`.trim(),
  approx: true,
});

